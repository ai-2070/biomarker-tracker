export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** A glyph as rows (top first) of 5 booleans, or null for a gap. */
export function glyph(ch: string): boolean[][] | null {
  const raw = RAW[ch] ?? RAW[ch.toUpperCase()];
  if (!raw) return null;
  return raw.split(' ').map((row) => [...row].map((c) => c === '#'));
}
